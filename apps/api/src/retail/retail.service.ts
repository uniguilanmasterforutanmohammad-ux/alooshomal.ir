  async adminListProducts(query: {
    status?: string;
    q?: string;
    take?: number;
  }) {
    const take = Math.min(300, Math.max(1, query.take ?? 100));
    const q = query.q?.trim();
    return this.prisma.retailProduct.findMany({
      where: {
        ...(query.status ? { status: query.status } : {}),
        ...(q
          ? {
              OR: [
                { title: { contains: q, mode: 'insensitive' } },
                { sku: { contains: q, mode: 'insensitive' } },
                { category: { contains: q, mode: 'insensitive' } },
                { workspace: { name: { contains: q, mode: 'insensitive' } } },
              ],
            }
          : {}),
      },
      include: {
        workspace: { select: { id: true, name: true, publicSlug: true } },
        categoryRef: { select: { id: true, name: true } },
      },
      orderBy: [{ submittedAt: 'desc' }, { createdAt: 'desc' }],
      take,
    });
  }

  async reviewProduct(
    adminUserId: string,
    id: string,
    dto: ReviewRetailProductDto,
  ) {
    const product = await this.prisma.retailProduct.findUnique({
      where: { id },
    });
    if (!product) throw new NotFoundException('محصول پیدا نشد');
    if (product.status !== 'PENDING_REVIEW') {
      throw new BadRequestException(
        'این محصول در صف بررسی مدیر نیست.',
      );
    }
    return this.prisma.retailProduct.update({
      where: { id },
      data: {
        status: dto.approve ? 'PUBLISHED' : 'REJECTED',
        publishedAt: dto.approve ? new Date() : null,
        reviewedAt: new Date(),
        reviewedById: adminUserId,
        rejectionReason: dto.approve
          ? null
          : dto.reason?.trim() || 'بدون توضیح',
      },
    });
  }

