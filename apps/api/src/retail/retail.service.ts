  private async uniqueCategorySlug(name: string, ignoreId?: string) {
    const base =
      name
        .trim()
        .toLowerCase()
        .replace(/[^\p{L}\p{N}]+/gu, '-')
        .replace(/^-+|-+$/g, '')
        .slice(0, 60) || 'category';
    let candidate = base;
    for (let index = 2; index < 500; index += 1) {
      const exists = await this.prisma.retailProductCategory.findFirst({
        where: { slug: candidate, ...(ignoreId ? { id: { not: ignoreId } } : {}) },
        select: { id: true },
      });
      if (!exists) return candidate;
      candidate = `${base}-${index}`;
    }
    return `${base}-${Date.now()}`;
  }

