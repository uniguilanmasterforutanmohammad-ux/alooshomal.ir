  private async workspaceId(userId: string): Promise<string> {
    return this.modules.getWorkspaceId(userId);
  }

  private async uniqueSlug(base: string): Promise<string> {
    const cleaned =
      base
        .trim()
        .toLowerCase()
        .replace(/[^\p{L}\p{N}]+/gu, '-')
        .replace(/^-+|-+$/g, '')
        .slice(0, 80) || 'product';
    let candidate = cleaned;
    for (let index = 2; index < 1000; index += 1) {
      const exists = await this.prisma.retailProduct.findUnique({
        where: { slug: candidate },
        select: { id: true },
      });
      if (!exists) return candidate;
      candidate = `${cleaned}-${index}`;
    }
    return `${cleaned}-${Date.now()}`;
  }

  private publishedAt(status: string, current: Date | null): Date | null {
    if (status !== 'PUBLISHED') return current;
    return current ?? new Date();
  }

  /** Sequential, workspace-scoped product code generated by the system. */
  private async generateSku(workspaceId: string): Promise<string> {
    const prefix = `SKU-${workspaceId.slice(-4).toUpperCase()}`;
    const count = await this.prisma.retailProduct.count({
      where: { workspaceId },
    });
    for (let attempt = 0; attempt < 50; attempt += 1) {
      const candidate = `${prefix}-${String(count + 1 + attempt).padStart(4, '0')}`;
      const exists = await this.prisma.retailProduct.findFirst({
        where: { workspaceId, sku: candidate },
        select: { id: true },
      });
      if (!exists) return candidate;
    }
    return `${prefix}-${randomBytes(3).toString('hex').toUpperCase()}`;
  }

  private async resolveCategory(
    categoryId: string | null | undefined,
    fallbackName?: string | null,
  ): Promise<{ categoryId: string | null; category: string | null }> {
    if (categoryId) {
      const category = await this.prisma.retailProductCategory.findUnique({
        where: { id: categoryId },
      });
      if (!category || !category.isActive) {
        throw new BadRequestException('دسته‌بندی انتخاب‌شده معتبر نیست.');
      }
      return { categoryId: category.id, category: category.name };
    }
    const name = fallbackName?.trim();
    return { categoryId: null, category: name || null };
  }

  private async assertGallerySize(gallery: string[] | undefined) {
    if (!gallery) return;
    const max = await this.settings.getRetailProductMaxImages();
    if (gallery.length > max) {
      throw new BadRequestException(
        `حداکثر ${max} تصویر برای هر محصول مجاز است.`,
      );
    }
  }

  private sellerStatus(status?: string): RetailProductStatus {
    if (status === 'PENDING_REVIEW') return 'PENDING_REVIEW';
    if (status === 'ARCHIVED') return 'ARCHIVED';
    return 'DRAFT';
  }

  /** Trim, drop empty rows and cap the specification list. */
  private normaliseSpecs(
    specs?: Array<{ name: string; value: string }>,
  ): Prisma.InputJsonValue | typeof Prisma.DbNull | undefined {
    if (specs === undefined) return undefined;
    const cleaned = specs
      .map((spec) => ({
        name: (spec.name ?? '').trim(),
        value: (spec.value ?? '').trim(),
      }))
      .filter((spec) => spec.name && spec.value)
      .slice(0, 40);
    return cleaned.length > 0 ? cleaned : Prisma.DbNull;
  }

