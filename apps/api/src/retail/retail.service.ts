  private async shopSettingsOrDefault(workspaceId: string) {
    const settings = await this.prisma.retailShopSettings.findUnique({
      where: { workspaceId },
    });
    return settings ?? { workspaceId, ...DEFAULT_SHOP_SETTINGS };
  }

  async getShopSettings(userId: string) {
    const workspaceId = await this.workspaceId(userId);
    return this.shopSettingsOrDefault(workspaceId);
  }

  async updateShopSettings(userId: string, dto: UpsertShopSettingsDto) {
    const workspaceId = await this.workspaceId(userId);
    const neighborhoods = (dto.neighborhoods ?? [])
      .map((item) => item.trim())
      .filter(Boolean);
    const data = {
      ...(dto.city !== undefined ? { city: dto.city.trim() || null } : {}),
      ...(dto.neighborhoods !== undefined ? { neighborhoods } : {}),
      ...(dto.deliveryFee !== undefined ? { deliveryFee: dto.deliveryFee } : {}),
      ...(dto.deliveryEnabled !== undefined
        ? { deliveryEnabled: dto.deliveryEnabled }
        : {}),
      ...(dto.snapEnabled !== undefined ? { snapEnabled: dto.snapEnabled } : {}),
      ...(dto.pickupEnabled !== undefined
        ? { pickupEnabled: dto.pickupEnabled }
        : {}),
      ...(dto.pickupAddress !== undefined
        ? { pickupAddress: dto.pickupAddress.trim() || null }
        : {}),
      ...(dto.pickupHours !== undefined
        ? { pickupHours: dto.pickupHours.trim() || null }
        : {}),
      ...(dto.supportPhone !== undefined
        ? { supportPhone: dto.supportPhone.trim() || null }
        : {}),
      ...(dto.returnPolicy !== undefined
        ? { returnPolicy: dto.returnPolicy.trim() || null }
        : {}),
      ...(dto.reservationMinutes !== undefined
        ? { reservationMinutes: dto.reservationMinutes }
        : {}),
    };
    return this.prisma.retailShopSettings.upsert({
      where: { workspaceId },
      update: data,
      create: { workspaceId, ...DEFAULT_SHOP_SETTINGS, ...data },
    });
  }

  // -------------------------------------------------------------------------
  //  Products (owner)
  // -------------------------------------------------------------------------

  async listProducts(userId: string, q?: string) {
    const workspaceId = await this.workspaceId(userId);
    return this.prisma.retailProduct.findMany({
      where: {
        workspaceId,
        ...(q
          ? {
              OR: [
                { title: { contains: q, mode: 'insensitive' } },
                { sku: { contains: q, mode: 'insensitive' } },
                { category: { contains: q, mode: 'insensitive' } },
              ],
            }
          : {}),
      },
      orderBy: [{ createdAt: 'desc' }],
      take: 300,
    });
  }

  async createProduct(userId: string, dto: CreateProductDto) {
    const workspaceId = await this.workspaceId(userId);
    const slug = await this.uniqueSlug(dto.slug || dto.title);
    const status = this.sellerStatus(dto.status);
    const category = await this.resolveCategory(dto.categoryId, dto.category);
    await this.assertGallerySize(dto.gallery);
    const sku = await this.generateSku(workspaceId);
    return this.prisma.$transaction(async (tx) => {
      const product = await tx.retailProduct.create({
        data: {
          workspaceId,
          slug,
          title: dto.title,
          description: dto.description,
          category: category.category,
          categoryId: category.categoryId,
          sku,
          price: dto.price ?? 0,
          compareAtPrice: dto.compareAtPrice,
          costPrice: dto.costPrice ?? 0,
          stock: dto.stock ?? 0,
          lowStockThreshold: dto.lowStockThreshold ?? 0,
          unit: dto.unit ?? 'عدد',
          brand: dto.brand?.trim() || null,
          specs: this.normaliseSpecs(dto.specs),
          imageUrl: dto.imageUrl,
          gallery: dto.gallery ?? [],
          status,
          publishedAt: null,
          submittedAt: status === 'PENDING_REVIEW' ? new Date() : null,
        },
      });
      if (product.stock > 0) {
        await tx.retailStockMovement.create({
          data: {
            workspaceId,
            productId: product.id,
            kind: 'IN',
            quantity: product.stock,
            note: 'موجودی اولیه',
          },
        });
      }
      return product;
    });
  }

  async updateProduct(userId: string, id: string, dto: UpdateProductDto) {
    const workspaceId = await this.workspaceId(userId);
    const product = await this.prisma.retailProduct.findFirst({
      where: { id, workspaceId },
    });
    if (!product) throw new NotFoundException('محصول پیدا نشد');
    const status = dto.status
      ? this.sellerStatus(dto.status)
      : product.status;
    const category =
      dto.categoryId !== undefined
        ? await this.resolveCategory(dto.categoryId, dto.category)
        : dto.category !== undefined
          ? { category: dto.category?.trim() || null }
          : {};
    await this.assertGallerySize(dto.gallery);
    const submitted = status === 'PENDING_REVIEW' && product.status !== 'PENDING_REVIEW';
    const sku = product.sku ?? (await this.generateSku(workspaceId));
    return this.prisma.retailProduct.update({
      where: { id },
      data: {
        ...(dto.title !== undefined ? { title: dto.title } : {}),
        ...(dto.description !== undefined ? { description: dto.description } : {}),
        ...category,
        sku,
        ...(dto.price !== undefined ? { price: dto.price } : {}),
        ...(dto.compareAtPrice !== undefined
          ? { compareAtPrice: dto.compareAtPrice }
          : {}),
        ...(dto.costPrice !== undefined ? { costPrice: dto.costPrice } : {}),
        ...(dto.lowStockThreshold !== undefined
          ? { lowStockThreshold: dto.lowStockThreshold }
          : {}),
        ...(dto.unit !== undefined ? { unit: dto.unit } : {}),
        ...(dto.brand !== undefined
          ? { brand: dto.brand?.trim() || null }
          : {}),
        ...(dto.specs !== undefined
          ? { specs: this.normaliseSpecs(dto.specs) }
          : {}),
        ...(dto.imageUrl !== undefined ? { imageUrl: dto.imageUrl } : {}),
        ...(dto.gallery !== undefined ? { gallery: dto.gallery } : {}),
        ...(dto.stock !== undefined ? { stock: dto.stock } : {}),
        status,
        publishedAt:
          status === 'PUBLISHED'
            ? this.publishedAt(status, product.publishedAt)
            : null,
        ...(submitted
          ? {
              submittedAt: new Date(),
              reviewedAt: null,
              reviewedById: null,
              rejectionReason: null,
            }
          : {}),
      },
    });
  }

  async removeProduct(userId: string, id: string) {
    const workspaceId = await this.workspaceId(userId);
    const product = await this.prisma.retailProduct.findFirst({
      where: { id, workspaceId },
      select: { id: true },
    });
    if (!product) throw new NotFoundException('محصول پیدا نشد');
    await this.prisma.retailProduct.delete({ where: { id } });
    return { id };
  }

