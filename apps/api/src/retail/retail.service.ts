  async createCategory(dto: CreateRetailCategoryDto) {
    const name = dto.name.trim();
    const exists = await this.prisma.retailProductCategory.findUnique({
      where: { name },
    });
    if (exists) throw new ConflictException('این دسته‌بندی قبلاً ثبت شده است.');
    return this.prisma.retailProductCategory.create({
      data: {
        name,
        slug: await this.uniqueCategorySlug(name),
        sortOrder: dto.sortOrder ?? 0,
        isActive: dto.isActive ?? true,
      },
    });
  }

  async updateCategory(id: string, dto: UpdateRetailCategoryDto) {
    const category = await this.prisma.retailProductCategory.findUnique({
      where: { id },
    });
    if (!category) throw new NotFoundException('دسته‌بندی پیدا نشد');
    const name = dto.name?.trim() ?? category.name;
    if (name !== category.name) {
      const exists = await this.prisma.retailProductCategory.findUnique({
        where: { name },
      });
      if (exists && exists.id !== id) {
        throw new ConflictException('این دسته‌بندی قبلاً ثبت شده است.');
      }
    }
    return this.prisma.$transaction(async (tx) => {
      const updated = await tx.retailProductCategory.update({
        where: { id },
        data: {
          ...(dto.name !== undefined ? { name } : {}),
          ...(dto.name !== undefined
            ? { slug: await this.uniqueCategorySlug(name, id) }
            : {}),
          ...(dto.sortOrder !== undefined ? { sortOrder: dto.sortOrder } : {}),
          ...(dto.isActive !== undefined ? { isActive: dto.isActive } : {}),
        },
      });
      if (dto.name !== undefined) {
        await tx.retailProduct.updateMany({
          where: { categoryId: id },
          data: { category: name },
        });
      }
      return updated;
    });
  }

  async deleteCategory(id: string) {
    const category = await this.prisma.retailProductCategory.findUnique({
      where: { id },
    });
    if (!category) throw new NotFoundException('دسته‌بندی پیدا نشد');
    await this.prisma.retailProductCategory.delete({ where: { id } });
    return { id };
  }

